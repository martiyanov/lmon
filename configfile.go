const defaultTargetHost = "8.8.8.8"

type configFlags struct {
	path     string
	noConfig bool
	save     bool
}

// splitConfigFlags вынимает --config/--no-config/--save-config до flag.Parse:
// сам конфиг должен быть прочитан раньше остальных флагов.
func splitConfigFlags(args []string) ([]string, configFlags, error) {
	cf := configFlags{path: defaultConfigPath()}
	rest := make([]string, 0, len(args))
	for i := 0; i < len(args); i++ {
		a := args[i]
		switch {
		case a == "--config":
			if i+1 >= len(args) {
				return nil, cf, errors.New("--config: expected a path")
			}
			i++
			cf.path = args[i]
		case strings.HasPrefix(a, "--config="):
			cf.path = strings.TrimPrefix(a, "--config=")
			if cf.path == "" {
				return nil, cf, errors.New("--config: expected a path")
			}
		case a == "--no-config":
			cf.noConfig = true
		case strings.HasPrefix(a, "--no-config="):
			v, err := parseConfigBool(strings.TrimPrefix(a, "--no-config="))
			if err != nil {
				return nil, cf, fmt.Errorf("--no-config: %w", err)
			}
			cf.noConfig = v
		case a == "--save-config":
			cf.save = true
		case strings.HasPrefix(a, "--save-config="):
			v, err := parseConfigBool(strings.TrimPrefix(a, "--save-config="))
			if err != nil {
				return nil, cf, fmt.Errorf("--save-config: %w", err)
			}
			cf.save = v
		default:
			rest = append(rest, a)
		}
	}
	return rest, cf, nil
}

func defaultConfigPath() string {
	if p := os.Getenv("LMON_CONFIG"); p != "" {
		return p
	}
	if runtime.GOOS == "windows" {
		if d, err := os.UserConfigDir(); err == nil {
			return filepath.Join(d, "lmon", "config")
		}
	}
	if x := os.Getenv("XDG_CONFIG_HOME"); x != "" {
		return filepath.Join(x, "lmon", "config")
	}
	if h, err := os.UserHomeDir(); err == nil && h != "" {
		return filepath.Join(h, ".config", "lmon", "config")
	}
	return "lmon.conf"
}

func parseConfigBool(s string) (bool, error) {
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "1", "true", "yes", "on":
		return true, nil
	case "0", "false", "no", "off":
		return false, nil
	}
	return false, fmt.Errorf("expected true/false, got %q", s)
}

var configBoolKeys = map[string]bool{
	"bars": true, "blocks": true, "hybrid": true, "compact": true,
	"rain": true, "matrix": true, "horizontal": true, "mono": true,
	"resize-window": true, "three-columns": true,
	"cpu": true, "iowait": true, "swap": true, "disk": true,
	"disk-busy": true, "batt": true, "gpu": true, "gputemp": true,
	"all": true, "fans": true, "fans-all": true, "gpu-power": true,
	"nvme": true, "disk-io": true, "net-rate": true, "psi": true,
	"system": true, "cpu-power": true, "nvme-smart": true,
	"disk-rate": true, "pressure": true,
	"no-hints": true, "symbols": true, "once": true,
	"gpu-list": true, "fans-list": true,
}

// loadConfigArgs превращает файл key=value в аргументы для flag.Parse.
// config-файл идёт перед CLI: CLI перекрывает конфиг, конфиг — env-дефолты.
func loadConfigArgs(path string) ([]string, error) {
	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("config %s: %w", path, err)
	}
	defer f.Close()
	var args []string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 4096), 1<<20)
	lineNo := 0
	for sc.Scan() {
		lineNo++
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, val, ok := strings.Cut(line, "=")
		key = strings.TrimSpace(strings.ReplaceAll(key, "_", "-"))
		key = strings.TrimPrefix(key, "--")
		if !ok {
			val = "true"
		}
		val = strings.TrimSpace(val)
		if key == "" || key == "config" || key == "no-config" || key == "save-config" {
			return nil, fmt.Errorf("config %s:%d: invalid key %q", path, lineNo, key)
		}
		if configBoolKeys[key] {
			b, err := parseConfigBool(val)
			if err != nil {
				return nil, fmt.Errorf("config %s:%d: %s: %w", path, lineNo, key, err)
			}
			if b {
				args = append(args, "--"+key)
			} else {
				args = append(args, "--"+key+"=false")
			}
			continue
		}
		if val == "" {
			args = append(args, "--"+key+"=")
		} else {
			args = append(args, "--"+key+"="+val)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("config %s: %w", path, err)
	}
	return args, nil
}

func writeConfigFile(cfg config, path string) error {
	if path == "" {
		path = defaultConfigPath()
	}
	var b strings.Builder
	b.WriteString("# lmon config — generated by `lmon --save-config`\n")
	b.WriteString("# CLI flags override this file; --no-config skips it.\n\n")
	write := func(k, v string) { fmt.Fprintf(&b, "%s=%s\n", k, v) }

	if cfg.target != defaultTargetHost {
		write("target", cfg.target)
	}
	if cfg.gw != "" {
		write("gw", cfg.gw)
	}
	if cfg.interval != time.Second {
		write("interval", strconv.FormatFloat(cfg.interval.Seconds(), 'f', -1, 64))
	}
	if len(cfg.cols) > 0 {
		write("cols", strings.Join(cfg.cols, ","))
	}
	if cfg.all {
		write("all", "true")
	}
	for _, p := range cfg.pings {
		write("ping", p.name+"="+p.host)
	}
	if len(cfg.thresholds) > 0 {
		keys := make([]string, 0, len(cfg.thresholds))
		for k := range cfg.thresholds {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, 0, len(keys))
		for _, k := range keys {
			t := cfg.thresholds[k]
			parts = append(parts, fmt.Sprintf("%s=%d/%d/%d", k, t[0], t[1], t[2]))
		}
		write("thresholds", strings.Join(parts, ","))
	}
	if cfg.blocks {
		write("bars", "true")
	}
	if cfg.hybrid {
		write("hybrid", "true")
	}
	if cfg.compact {
		write("compact", "true")
	}
	if cfg.horizontal {
		write("horizontal", "true")
	}
	if cfg.labelsFull {
		write("labels", "full")
	}
	if cfg.rain {
		write("rain", "true")
	}
	if cfg.matrixPalette {
		write("matrix", "true")
	}
	if cfg.mono {
		write("mono", "true")
	}
	if !cfg.resizeWindow {
		write("resize-window", "false")
	}
	if cfg.threeColumns {
		write("three-columns", "true")
	}
	if cfg.noHints {
		write("no-hints", "true")
	}
	if cfg.tempCmd != "" {
		write("temp-cmd", cfg.tempCmd)
	}
	if cfg.symbols {
		write("symbols", "true")
	}
	if !cfg.all {
		flags := []struct {
			k  string
			on bool
		}{
			{"cpu", cfg.cpu}, {"iowait", cfg.iowait}, {"swap", cfg.swap},
			{"disk", cfg.disk}, {"disk-busy", cfg.diskBusy}, {"batt", cfg.batt},
			{"gpu", cfg.gpu}, {"gputemp", cfg.gputemp}, {"fans", cfg.fans},
			{"fans-all", cfg.fansAll}, {"gpu-power", cfg.gpuPower},
			{"nvme", cfg.nvme}, {"disk-io", cfg.diskIO}, {"net-rate", cfg.netRate},
			{"psi", cfg.psi}, {"system", cfg.system}, {"cpu-power", cfg.cpuPower},
			{"nvme-smart", cfg.nvmeSmart},
		}
		for _, f := range flags {
			if f.on {
				write(f.k, "true")
			}
		}
	}
	if len(cfg.gpuIdx) > 1 || (len(cfg.gpuIdx) == 1 && cfg.gpuIdx[0] != 0) {
		parts := make([]string, len(cfg.gpuIdx))
		for i, n := range cfg.gpuIdx {
			parts[i] = strconv.Itoa(n)
		}
		write("gpu-index", strings.Join(parts, ","))
	}
	if cfg.lang == "ru" {
		write("lang", "ru")
	}

	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("config %s: %w", path, err)
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o600); err != nil {
		return fmt.Errorf("config %s: %w", path, err)
	}
	if err := os.Rename(tmp, path); err != nil {
		return fmt.Errorf("config %s: %w", path, err)
	}
	return nil
}
